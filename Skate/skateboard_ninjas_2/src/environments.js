export const ENV_LIST = Object.values(ENVIRONMENTS);

// Random environment, never the previous one.
export function pickEnvironment(lastId, rng = Math.random) {
  const options = ENV_LIST.filter((e) => e.id !== lastId);
  return options[Math.floor(rng() * options.length)];
}
